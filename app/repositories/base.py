# =========================================================
# Contratos (interfaces) de acceso a datos. Los servicios dependen
# de estos protocolos, no de Supabase: en la Fase 3 se agregan
# implementaciones SQLAlchemy intercambiables (HU-B-301).
# =========================================================
from collections.abc import Callable
from contextlib import AbstractContextManager
from typing import Any, Protocol

Fila = dict[str, Any]

# Abre una unidad de trabajo (sesion con commit/rollback). Hoy: session_scope().
AbrirSesion = Callable[[], AbstractContextManager[Any]]


class LectorBloques(Protocol):
    def listar(self) -> list[Fila]: ...


class LectorLecciones(Protocol):
    def listar(self) -> list[Fila]: ...
    def obtener(self, leccion_id: int) -> Fila | None: ...


class LectorEjercicios(Protocol):
    def listar(self) -> list[Fila]: ...


class LectorAcordes(Protocol):
    def listar(self) -> list[Fila]: ...


class VerificadorExistencia(Protocol):
    def existe(self, contenido_id: int) -> bool: ...


class RepositorioPerfiles(Protocol):
    """Opera dentro de la sesion que abre el servicio (unidad de trabajo)."""

    def obtener(self, sesion: Any, usuario_id: str) -> Fila | None: ...
    def obtener_para_actualizar(self, sesion: Any, usuario_id: str) -> Fila | None: ...
    def contar_por_rol(self, sesion: Any, rol: str) -> int: ...
    def actualizar_rol(self, sesion: Any, usuario_id: str, rol: str) -> Fila: ...
    def email_de(self, sesion: Any, usuario_id: str) -> str | None: ...
    def actualizar_nombre(self, sesion: Any, usuario_id: str, cambios: dict[str, str]) -> Fila: ...
    def actualizar_permiso_nombre(
        self, sesion: Any, usuario_ids: list[str], permitido: bool
    ) -> list[str]: ...


class RepositorioProgresoContenido(Protocol):
    """Progreso por leccion y por ejercicio. Opera dentro de la sesion del servicio."""

    def listar_lecciones(self, sesion: Any, estudiante_id: str) -> list[Fila]: ...
    def listar_ejercicios(self, sesion: Any, estudiante_id: str) -> list[Fila]: ...
    def registrar_leccion(
        self, sesion: Any, estudiante_id: str, leccion_id: int, *, porcentaje: int, completado: bool
    ) -> Fila: ...
    def registrar_ejercicio(
        self,
        sesion: Any,
        estudiante_id: str,
        ejercicio_id: int,
        *,
        porcentaje: int,
        completado: bool,
        mejor_bpm: int | None,
    ) -> Fila: ...
    def totales_catalogo(self, sesion: Any) -> dict[str, int]: ...
    def actividad(
        self, sesion: Any, estudiante_id: str, *, dias: int, limite: int
    ) -> dict[str, list[Fila]]: ...


class RepositorioCursos(Protocol):
    """Cursos, inscripciones y ruta del curso. Opera dentro de la sesion del servicio."""

    def crear(self, sesion: Any, datos: Fila) -> Fila: ...
    def obtener(self, sesion: Any, curso_id: int, *, bloquear: bool = False) -> Fila | None: ...
    def obtener_activo_por_codigo(self, sesion: Any, codigo: str) -> Fila | None: ...
    def inscribir(self, sesion: Any, curso_id: int, estudiante_id: str) -> None: ...
    def archivar(self, sesion: Any, curso_id: int) -> Fila: ...
    def puede_ver(self, sesion: Any, curso_id: int, usuario_id: str) -> bool: ...
    def bloques_publicados(self, sesion: Any, bloque_ids: set[int]) -> set[int]: ...
    def reemplazar_ruta(self, sesion: Any, curso_id: int, ruta: list[tuple[int, int]]) -> None: ...
    def cursos_de_estudiante(self, sesion: Any, estudiante_id: str) -> list[Fila]: ...
    def listar_de_docente(
        self, sesion: Any, docente_id: str | None, *, archivados: bool
    ) -> list[Fila]: ...
    def ruta(self, sesion: Any, curso_id: int) -> list[Fila]: ...
    def contar_estudiantes(self, sesion: Any, curso_id: int) -> int: ...
    def actualizar(self, sesion: Any, curso_id: int, cambios: Fila) -> Fila: ...
    def retirar(self, sesion: Any, curso_id: int, estudiante_id: str) -> bool: ...
    def crear_retroalimentacion(self, sesion: Any, datos: Fila) -> Fila: ...
    def marcar_leidas(self, sesion: Any, curso_id: int, estudiante_id: str) -> None: ...


class RepositorioCodigos(Protocol):
    """Codigos de un solo uso. Opera dentro de la sesion del servicio."""

    def invalidar_abiertos(self, sesion: Any, usuario_id: str, proposito: str) -> None: ...
    def crear(
        self,
        sesion: Any,
        *,
        usuario_id: str,
        proposito: str,
        codigo_hash: str,
        email_destino: str | None,
        vigencia_min: int,
    ) -> None: ...
    def hay_reciente(
        self, sesion: Any, usuario_id: str, proposito: str, *, segundos: int
    ) -> bool: ...
    def obtener_abierto_vigente(
        self, sesion: Any, usuario_id: str, proposito: str
    ) -> Fila | None: ...
    def obtener_abierto_por_hash(
        self, sesion: Any, proposito: str, codigo_hash: str
    ) -> Fila | None: ...
    def registrar_fallo(self, sesion: Any, codigo_id: str) -> None: ...
    def consumir(self, sesion: Any, codigo_id: str) -> bool: ...


class RepositorioCuentas(Protocol):
    """Cuentas ubicadas por correo (auth.users). Opera dentro de la sesion del servicio."""

    def buscar_pendiente_por_email(self, sesion: Any, email: str) -> Fila | None: ...
    def buscar_verificada_por_email(self, sesion: Any, email: str) -> Fila | None: ...
    def marcar_verificada(self, sesion: Any, usuario_id: str) -> None: ...
    def datos_de_aviso(self, sesion: Any, usuario_id: str) -> Fila | None: ...
    def correo_en_uso(self, sesion: Any, email: str, *, excepto_id: str) -> bool: ...
    def cambiar_correo(self, sesion: Any, usuario_id: str, email: str) -> None: ...
    def fijar_contrasena(self, sesion: Any, usuario_id: str, password: str) -> None: ...
    def cerrar_sesiones(
        self, sesion: Any, usuario_id: str, *, excepto: str | None = None
    ) -> None: ...


class RepositorioEnviosCorreo(Protocol):
    """Bitacora de correos. Opera dentro de la sesion del servicio."""

    def registrar(
        self, sesion: Any, *, usuario_id: str | None, tipo: str, estado: str, error: str | None
    ) -> None: ...
